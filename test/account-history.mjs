import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createServerDatabase } from '../src/server-database.mjs';
import { createAccountHistory } from '../src/account-history.mjs';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'account-history-'));
let db = createServerDatabase({ outputRoot: dir });
let h = createAccountHistory(db);
const job = { id: 'sample-id', createdAt: '2026-01-01T00:00:00Z', status: 'queued' };
h.initialize(job);
h.start(job, 'run1', 'full', 'initial'); job.status = 'completed'; h.finish(job); h.finish(job);
job.status = 'queued'; h.start(job, 'run2', 'full', 'manual_relogin'); job.status = 'failed'; h.finish(job);
assert.equal(h.detail(job).firstAddedAt, job.createdAt);
assert.deepEqual(h.detail(job).events.map(e => e.status), ['failed', 'completed']);
db.close(); db = createServerDatabase({ outputRoot: dir }); h = createAccountHistory(db);
assert.equal(h.detail(job).total, 2);
assert.equal(h.detail(job).firstAddedAt, job.createdAt);
const old = { id: 'old-id' }; db.saveJob(old.id, { created_at: '2025-01-01T00:00:00Z' });
assert.equal(h.detail(old).firstAddedAt, '2025-01-01T00:00:00Z'); assert.equal(h.detail(old).legacy, true); assert.equal(h.detail(old).total, 0);
assert.equal(h.detail({ id: 'unknown' }).firstAddedAt, null);
for (let i = 0; i < 51; i++) h.start(old, 'run-' + i, 'refresh', 'token_refresh');
assert.equal(h.detail(old).events.length, 50); assert.equal(h.detail(old, 2).events.length, 1);
assert.equal(h.detail(old, 2).events[0].status, 'unknown');
db.deleteJob(old.id); assert.equal(db.get('account-history', old.id), null);
db.close(); fs.rmSync(dir, { recursive: true });
console.log('account history: creation, repeated login, terminal outcome, restart, legacy, pagination and deletion passed');
