import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createAccountLifecycle, resolveAccountTerms, normalizeAccountArea, isRetiredAccountFailure } from "../src/account-lifecycle.mjs";
import { createServerDatabase } from "../src/server-database.mjs";

const root = await fs.mkdtemp(path.join(os.tmpdir(), "account-lifecycle-"));
let database = createServerDatabase({ outputRoot: root });
try {
  let lifecycle = createAccountLifecycle(database);
  const unsetEmail = "unset@example.invalid";
  lifecycle.initialize(unsetEmail);
  assert.equal(lifecycle.public(unsetEmail).accountTerm, null, "creation without an explicit type remains unset");
  lifecycle.initialize(unsetEmail, "long");
  assert.equal(lifecycle.public(unsetEmail).accountTerm, null, "initialization never classifies an existing unset account");
  lifecycle.initialize("explicit-null@example.invalid", null);
  assert.equal(lifecycle.public("explicit-null@example.invalid").accountTerm, null);
  const email = "TEST@example.invalid";
  lifecycle.initialize(email, "short");
  assert.equal(lifecycle.public(email).accountTerm, "short");
  assert.equal(lifecycle.public(email).firstAuthorizedAt, null);
  lifecycle.authorized(email, "2026-01-01T00:00:00Z", "full");
  lifecycle.authorized(email, "2026-01-02T00:00:00Z", "refresh");
  assert.equal(lifecycle.public(email).firstAuthorizedAt, "2026-01-01T00:00:00.000Z");
  assert.equal(lifecycle.public(email).firstAuthorizedAtSource, "recorded");
  const logout = { operationId: "logout-1", action: "logout-all", startedAt: "2026-01-03T00:00:00Z",
    result: { stage: "logout_requested", logout_accepted: true, logoutAcceptedAt: "2026-01-03T00:01:00Z" } };
  lifecycle.logout(email, logout);
  assert.equal(lifecycle.public(email).restingSince, "2026-01-03T00:01:00.000Z");
  assert.equal(lifecycle.public(email).restingReason, "logout_accepted");
  lifecycle.authorized(email, "2026-01-03T00:01:00Z", "full");
  assert.equal(lifecycle.public(email).resting, true, "same timestamp does not prove a later login");
  lifecycle.authorized(email, "2026-01-04T00:00:00Z", "refresh");
  assert.equal(lifecycle.public(email).resting, true, "refresh alone cannot end rest");
  lifecycle.setTerm(email, "long");
  assert.equal(lifecycle.public(email).resting, true, "tag editing cannot end rest");
  database.close(); database = createServerDatabase({ outputRoot: root, mustExist: true });
  lifecycle = createAccountLifecycle(database);
  assert.equal(lifecycle.public(email).accountTerm, "long");
  assert.equal(lifecycle.public(unsetEmail).accountTerm, null, "unset classification survives restart");
  assert.equal(lifecycle.public(email).resting, true);
  lifecycle.authorized(email, "2026-01-05T00:00:00Z", "full");
  assert.equal(lifecycle.public(email).resting, false);
  lifecycle.logout(email, logout);
  assert.equal(lifecycle.public(email).resting, false, "replaying old logout does not undo a later successful login");
  lifecycle.logout(email, { ...logout, operationId: "logout-2", result: { stage: "logout_requested", updatedAt: "2026-01-06T00:00:00Z" } });
  assert.equal(lifecycle.public(email).restingReason, "logout_requested");
  assert.equal(lifecycle.public(email).resting, true);
  const beforeRetire = lifecycle.public(email);
  lifecycle.retire(email, "账号已被上游删除", "2026-01-07T00:00:00Z");
  assert.deepEqual({ ...lifecycle.public(email), retired: false, retiredAt: null, retiredReason: null }, beforeRetire, "retirement preserves type, first authorization and logout state");
  assert.equal(lifecycle.public(email).retired, true);
  lifecycle.retire(email, "再次确认删除", "2026-01-08T00:00:00Z");
  assert.equal(lifecycle.public(email).retiredAt, "2026-01-07T00:00:00.000Z", "repeat classification preserves the retirement time");
  lifecycle.authorized(email, "2026-01-08T00:00:00Z", "refresh");
  assert.equal(lifecycle.public(email).retired, true, "refresh alone cannot recover a retired account");
  database.close(); database = createServerDatabase({ outputRoot: root, mustExist: true });
  lifecycle = createAccountLifecycle(database);
  assert.equal(lifecycle.public(email).retired, true);
  lifecycle.authorized(email, "2026-01-09T00:00:00Z", "full");
  assert.equal(lifecycle.public(email).retired, false);
  assert.equal(lifecycle.public(email).retiredAt, null);
  assert.equal(lifecycle.public(email).retiredReason, null);
  assert.equal(lifecycle.public(email).firstAuthorizedAt, beforeRetire.firstAuthorizedAt);
  lifecycle.rest(email, "2026-01-10T00:00:00Z");
  assert.equal(lifecycle.public(email).restingReason, "manual");
  lifecycle.authorized(email, "2026-01-11T00:00:00Z", "refresh");
  assert.equal(lifecycle.public(email).restingReason, "manual", "refresh cannot release a manual rest");
  database.close(); database = createServerDatabase({ outputRoot: root, mustExist: true });
  lifecycle = createAccountLifecycle(database);
  assert.equal(lifecycle.public(email).restingSince, "2026-01-10T00:00:00.000Z");
  lifecycle.logout(email, { ...logout, result: { stage: "logout_requested", updatedAt: "2026-01-12T00:00:00Z" } });
  assert.equal(lifecycle.public(email).restingReason, "logout_requested", "a later logout retains its actual status");
  lifecycle.authorized(email, "2026-01-13T00:00:00Z", "full");
  assert.equal(lifecycle.public(email).resting, false);
  lifecycle.retire(email, "手动移入废号区", "2026-01-14T00:00:00Z");
  assert.throws(() => lifecycle.rest(email), /成功登录/);
  for (const value of ["account_deactivated", 'HTTP 403 {"code":"account_deleted"}', "You do not have an account because it has been deleted or deactivated."]) assert.equal(isRetiredAccountFailure(value), true, value);
  for (const value of ["HTTP 401 token_revoked", "HTTP 403 access_denied", "IP blocked", "SECURITY_FACTOR_STATE: MFA disabled", "invalid_password", "wrong_email_or_password", "account not found locally", "Your account is not disabled", "USER_DISABLED", "Your account has been suspended", "account_deletedness"]) assert.equal(isRetiredAccountFailure(value), false, value);
  assert.equal(normalizeAccountArea("retired"), "retired");
  const legacy = { id: "legacy-1", email: "legacy@example.invalid", outputPath: path.join(root, "legacy-1", "sub2api-import-oauth.json") };
  database.saveJob(legacy.id, { last_auth_automated_at: "2026-01-01T00:00:00Z" });
  database.saveArtifact(legacy.outputPath, { exported_at: "2026-01-02T00:00:00Z" });
  lifecycle.backfill(legacy, [logout]);
  assert.equal(lifecycle.public(legacy.email).accountTerm, null);
  assert.equal(lifecycle.public(legacy.email).firstAuthorizedAt, "2026-01-01T00:00:00.000Z");
  assert.equal(lifecycle.public(legacy.email).firstAuthorizedAtSource, "historical");
  assert.equal(lifecycle.public(legacy.email).resting, true);
  database.saveArtifact(legacy.outputPath, { exported_at: "2026-02-01T00:00:00Z" });
  lifecycle.backfill(legacy, [logout]);
  assert.equal(lifecycle.public(legacy.email).resting, true, "a newer export may be refresh, so cannot prove full login");
  database.saveJob(legacy.id, { last_auth_automated_at: "2026-02-01T00:00:00Z" });
  lifecycle.backfill(legacy, [logout]);
  assert.equal(lifecycle.public(legacy.email).resting, false);
  const selected = [{ email: "A@example.invalid" }, { email: "b@example.invalid" }];
  const terms = resolveAccountTerms(selected, { accountTerm: "short", accountTerms: [{ email: "a@example.invalid", accountTerm: "long" }] });
  assert.equal(terms.term(selected[0].email), "long");
  assert.equal(terms.term(selected[1].email), "short");
  assert.equal(resolveAccountTerms(selected, {}).explicit(selected[0].email), false);
  for (const body of [{ accountTerm: "bad" }, { accountTerm: null }, { accountTerms: {} }, { accountTerms: [{ email: "c@example.invalid", accountTerm: "short" }] }, { accountTerms: [{ email: selected[0].email, accountTerm: "short" }, { email: selected[0].email, accountTerm: "long" }] }]) assert.throws(() => resolveAccountTerms(selected, body), /账号类型/);
  assert.throws(() => normalizeAccountArea("unknown"), /分区/);
  console.log("account lifecycle: encrypted persistence, exact/historical first authorization, logout rest, refresh exclusion, full-login release and validated terms passed");
} finally { database.close(); await fs.rm(root, { recursive: true, force: true }); }
